@dataclass(frozen=True)
class Eyes:
    shape: str = "bar"
    x: float = 28
    y: float = 82
    size: float = 13
    squint: float = 0
    tilt: float = 0


@dataclass(frozen=True)
class Brows:
    on: bool = False
    y: float = 52
    angle: float = 0
    length: float = 24


@dataclass(frozen=True)
class Mouth:
    y: float = 128
    width: float = 62
    curve: float = 0.5
    open: float = 0
    wave: float = 0
    flick: float = 0


@dataclass(frozen=True)
class FaceParams:
    width: float = 72
    height: float = 72
    squish: float = 0
    tilt: float = 0
    #: The open loop, in degrees. 360 leaves no outline at all — which is the
    #: default, because that is how these faces get drawn by hand.
    gap: float = 360
    eyes: Eyes = field(default_factory=Eyes)
    brows: Brows = field(default_factory=Brows)
    mouth: Mouth = field(default_factory=Mouth)
    marks: tuple[str, ...] = ()

    @staticmethod
    def from_dict(raw: dict[str, Any] | None) -> "FaceParams":
        raw = raw or {}
        base = FaceParams()
        eyes = dict(raw.get("eyes") or {})
        brows = dict(raw.get("brows") or {})
        mouth = dict(raw.get("mouth") or {})
        marks = raw.get("marks") or []
        return FaceParams(
            width=_num(raw.get("width"), base.width),
            height=_num(raw.get("height"), base.height),
            squish=_num(raw.get("squish"), base.squish),
            tilt=_num(raw.get("tilt"), base.tilt),
            gap=_num(raw.get("gap"), base.gap),
            eyes=Eyes(
                shape=eyes.get("shape") if eyes.get("shape") in EYE_SHAPES else base.eyes.shape,
                x=_num(eyes.get("x"), base.eyes.x),
                y=_num(eyes.get("y"), base.eyes.y),
                size=_num(eyes.get("size"), base.eyes.size),
                squint=_num(eyes.get("squint"), base.eyes.squint),
                tilt=_num(eyes.get("tilt"), base.eyes.tilt),
            ),
            brows=Brows(
                on=bool(brows.get("on", base.brows.on)),
                y=_num(brows.get("y"), base.brows.y),
                angle=_num(brows.get("angle"), base.brows.angle),
                length=_num(brows.get("length"), base.brows.length),
            ),
            mouth=Mouth(
                y=_num(mouth.get("y"), base.mouth.y),
                width=_num(mouth.get("width"), base.mouth.width),
                curve=_num(mouth.get("curve"), base.mouth.curve),
                open=_num(mouth.get("open"), base.mouth.open),
                wave=_num(mouth.get("wave"), base.mouth.wave),
                flick=_num(mouth.get("flick"), base.mouth.flick),
            ),
            marks=tuple(m for m in marks if m in MARKS),
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "width": self.width,
            "height": self.height,
            "squish": self.squish,
            "tilt": self.tilt,
            "gap": self.gap,
            "eyes": {
                "shape": self.eyes.shape,
                "x": self.eyes.x,
                "y": self.eyes.y,
                "size": self.eyes.size,
                "squint": self.eyes.squint,
                "tilt": self.eyes.tilt,
            },
            "brows": {
                "on": self.brows.on,
                "y": self.brows.y,
                "angle": self.brows.angle,
                "length": self.brows.length,
            },
            "mouth": {
                "y": self.mouth.y,
                "width": self.mouth.width,
                "curve": self.mouth.curve,
                "open": self.mouth.open,
                "wave": self.mouth.wave,
                "flick": self.mouth.flick,
            },
            "marks": list(self.marks),
        }


def _num(value: Any, fallback: float) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return float(fallback)
    if math.isnan(value) or math.isinf(value):
        return float(value)
    return float(value)


def clamp(value: float, limits: Sequence[float]) -> float:
    lo, hi = limits[0], limits[1]
    if math.isnan(value) or math.isinf(value):
        # face.ts uses Number.isFinite, so a non-finite value collapses to the
        # low end rather than clamping to the high one.
        return float(lo)
    return float(min(hi, max(lo, value)))


def clamp_to(key: str, value: float) -> float:
    return clamp(value, FACE_LIMITS[key])


def clamp_face(p: FaceParams) -> FaceParams:
    """Sanitise a whole face. A face can be ugly on purpose; never broken."""
    seen: list[str] = []
    for m in p.marks:  # dedupe, order-preserving, like `new Set`
        if m not in seen:
            seen.append(m)
    return replace(
        p,
        width=clamp_to("width", p.width),
        height=clamp_to("height", p.height),
        squish=clamp_to("squish", p.squish),
        tilt=clamp_to("tilt", p.tilt),
        gap=clamp_to("gap", p.gap),
        eyes=replace(
            p.eyes,
            x=clamp_to("eyeX", p.eyes.x),
            y=clamp_to("eyeY", p.eyes.y),
            size=clamp_to("eyeSize", p.eyes.size),
            squint=clamp_to("eyeSquint", p.eyes.squint),
            tilt=clamp_to("eyeTilt", p.eyes.tilt),
        ),
        brows=replace(
            p.brows,
            y=clamp_to("browY", p.brows.y),
            angle=clamp_to("browAngle", p.brows.angle),
            length=clamp_to("browLength", p.brows.length),
        ),
        mouth=replace(
            p.mouth,
            y=clamp_to("mouthY", p.mouth.y),
            width=clamp_to("mouthWidth", p.mouth.width),
            curve=clamp_to("mouthCurve", p.mouth.curve),
            open=clamp_to("mouthOpen", p.mouth.open),
            wave=clamp_to("mouthWave", p.mouth.wave),
            flick=clamp_to("mouthFlick", p.mouth.flick),
        ),
        marks=tuple(seen),
    )


