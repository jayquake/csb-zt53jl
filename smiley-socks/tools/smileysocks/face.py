"""
The face engine, ported from ``src/brand/face.ts``.

This is a deliberate second copy of the geometry, and the reason is worth
stating plainly: production art has to be generatable from a design record on a
machine with no browser and no Node — a queue worker, a CI step, someone's
laptop with a JSON file on it. Shelling out to a headless Chrome to find out
where a mouth goes is not a pipeline, it is a liability.

The cost of a second copy is drift, and that is paid for by
``tests/test_face.py``, which checks this module against a fixture generated by
the real TypeScript (``tests/production-fixtures.test.ts``). Change a curve on
either side and the other side goes red.

Everything here is pure: params in, primitives out. Face space is a 200x200
box, centre (100,100), exactly as in the TypeScript.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field, replace
from typing import Any, Iterable, Literal, Sequence

from .jsnum import fmt

FACE_BOX = 200
FACE_CX = 100.0
FACE_CY = 100.0

#: Mono-line weight, matched to Grinline so type and faces print as one system.
STROKE = 10.0

#: Past this gap the remaining sliver reads as a smudge, so we draw nothing.
NO_OUTLINE_AT = 340.0

RAD = math.pi / 180.0

EyeShape = Literal["bar", "tick", "round", "arc", "cross", "line", "spiral"]
Mark = Literal["tear", "sweat", "blush", "static", "zzz", "sparkle", "wink"]

EYE_SHAPES: tuple[str, ...] = (
    "bar",
    "tick",
    "round",
    "arc",
    "cross",
    "line",
    "spiral",
    "heart",
)
MARKS: tuple[str, ...] = (
    "tear",
    "sweat",
    "blush",
    "static",
    "zzz",
    "sparkle",
    "wink",
    "tongue",
)

#: The one source of truth for what a parameter is allowed to be. Mirrors
#: ``FACE_LIMITS`` in face.ts, and the fixture test asserts they are the same
#: numbers rather than trusting this comment.
FACE_LIMITS: dict[str, tuple[float, float]] = {
    "width": (52, 88),
    "height": (52, 88),
    "squish": (-18, 18),
    "tilt": (-14, 14),
    "gap": (0, 360),
    "eyeX": (14, 48),
    "eyeY": (52, 104),
    "eyeSize": (5, 26),
    "eyeSquint": (0, 1),
    "eyeTilt": (-40, 40),
    "browY": (26, 74),
    "browAngle": (-40, 40),
    "browLength": (12, 38),
    "mouthY": (104, 168),
    "mouthWidth": (24, 104),
    "mouthCurve": (-1, 1),
    "mouthOpen": (0, 1),
    "mouthWave": (0, 1),
    "mouthFlick": (0, 1),
}


